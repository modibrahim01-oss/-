import type { Tier } from "./tiers";

export type GridPoint = { x: number; y: number };

/**
 * تخطيط الأرباع: كل فئة نقاط بستانٌ قائم بذاته.
 *
 * الحلزون وحده كان يضع النبتة في الخانة التالية أيًّا كان نوعها، فتخرج
 * المزرعة خليطًا: فطر بجانب زهرة بجانب شجرة. هنا تملك كل فئة ربعًا من
 * الشبكة تنمو فيه من المركز للخارج، فتُقرأ المزرعة أربعة بساتين.
 *
 * وحجم البستان نفسه يروي القصة: بستان الـ‎١٠ يتّسع سريعًا وبستان الـ‎٥٠
 * يبقى صغيرًا، فيرى الطالب توزيع نقاطه من نظرة واحدة بلا أرقام.
 *
 * **القيد الحاكم:** الموضع دالّة صرفة في (الفئة، ترتيب النبتة داخل فئتها).
 * لا يعتمد على تاريخ المنح ولا على أعداد الفئات الأخرى — ولولا ذلك لانتقلت
 * نبتة زُرعت أمس لأن الطالب نال اليوم نقطة من فئة أخرى.
 *
 * مُطابِقة حرفيًا لـ quadrant_coord في supabase/migrations/0005_quadrant_layout.sql،
 * ويحرس التطابقَ اختبارُ tests/quadrant-parity.test.ts على مخرَج Postgres فعلي.
 */

/**
 * الربع الذي تملكه كل فئة: إشارتا المحورين.
 *
 * في المنظور المتساوي القياس يقع الربع (−،−) في الزاوية العليا من المعيّن،
 * أبعد نقطة عن الكاميرا. الأشجار المثمرة هناك باختيار المالك: هي أطول
 * النبتات، فوضعها في الخلف يجعلها تاجًا للمزرعة ولا يحجب شيئًا أمامها.
 * والشجيرات — أكثر النبتات عددًا — في الزاوية السفلى الأقرب إلى العين.
 */
const QUADRANT: Record<Tier, [number, number]> = {
  green: [1, 1], //   الزاوية السفلى
  yellow: [-1, 1], // اليسرى
  purple: [1, -1], // اليمنى
  red: [-1, -1], //   العليا
};

/**
 * الخانة رقم `n` في ربع مستوٍ، مرتّبة قشرةً قشرة من الزاوية للخارج.
 *
 * القشرة `s` فيها `2s−1` خانة والمجموع حتى نهايتها `s²`، فالجذر التربيعي
 * يعطي القشرة مباشرة بلا بحث ولا حلقة.
 */
function quarterCell(n: number): GridPoint {
  // تقدير القشرة ثم تصحيحه. التصحيح يحمي من خطأ الفاصلة العائمة عند
  // المربعات الكاملة: جذرٌ يعود ‎1.9999‎ بدل ‎2‎ يُنقص قشرةً فتقع النبتة على
  // المحور — أي خارج ربعها وفوق نبتة أخرى.
  let s = Math.floor(Math.sqrt(n)) + 1;
  while (s > 1 && n < (s - 1) ** 2) s -= 1;
  while (n >= s ** 2) s += 1;

  const r = n - (s - 1) ** 2;
  return r < s ? { x: s, y: r + 1 } : { x: 2 * s - 1 - r, y: s };
}

/** موضع النبتة رقم `n` (ترتيبها داخل فئتها، من الصفر) على الشبكة. */
export function quadrantCoord(tier: Tier, n: number): GridPoint {
  if (!Number.isInteger(n) || n < 0) {
    throw new RangeError(`quadrantCoord: rank must be a non-negative integer, got ${n}`);
  }
  const [sx, sy] = QUADRANT[tier];
  const c = quarterCell(n);
  return { x: c.x * sx, y: c.y * sy };
}
