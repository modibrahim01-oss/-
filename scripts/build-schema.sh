#!/usr/bin/env bash
# يجمع ملفات supabase/migrations/ بالترتيب في ملف واحد supabase/schema.sql
# ليُلصق دفعة واحدة في محرر SQL بلوحة Supabase.
#
# شغّله بعد أي تعديل على ملفات الترحيل:
#   ./scripts/build-schema.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/supabase/schema.sql"

{
  cat <<'HEADER'
-- ============================================================
-- إتقان المقاس — كل ملفات قاعدة البيانات مجمّعة في ملف واحد
-- ============================================================
-- الاستخدام: افتح مشروعك في Supabase ← SQL Editor ← New query،
-- الصق هذا الملف كاملًا، ثم اضغط Run. يُنفَّذ مرة واحدة فقط.
--
-- هذا الملف مولَّد آليًا من supabase/migrations/ بالترتيب الرقمي.
-- لا تعدّله يدويًا — عدّل الملفات الأصلية وأعد توليده بـ:
--   ./scripts/build-schema.sh
-- ============================================================

HEADER

  for f in "$ROOT"/supabase/migrations/0*.sql; do
    echo ""
    echo "-- ══════════════════════════════════════════════════════════"
    echo "-- $(basename "$f")"
    echo "-- ══════════════════════════════════════════════════════════"
    echo ""
    cat "$f"
  done
} > "$OUT"

echo "تم توليد $OUT ($(wc -l < "$OUT") سطرًا)"
